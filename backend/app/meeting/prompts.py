def call_tag(kind: str) -> str:
    """调用标识。Mock 供应商按它路由；对真实模型无害。"""
    return f"【调用类型：{kind}】"


BASE_SYSTEM_PROMPT = "\n\n".join([PLATFORM_RULES, OUTPUT_RULES])


def persona_block(participant: dict) -> str:
    """角色人设与模式纪律，一段冻结的内容。人设写具体的偏好，不写标签（详设 §11.5）。"""
    parts = [f"## 你的角色\n{(participant.get('system_prompt') or '').strip()}"]
    mode_rule = MODE_RULES.get(participant.get("mode") or "", "")
    if mode_rule:
        parts.append(mode_rule)
    return "\n\n".join(parts)
